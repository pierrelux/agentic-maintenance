P_TRUE_HINT = 0.5     # probability that a cause leaves a hint in the log
P_FALSE_HINT = 0.12   # probability that each other cause leaves a misleading hint


def maintenance_log(seed: int, hypothesis: str, alarm_date) -> list[dict]:
    """Episode-specific maintenance log: routine entries plus noisy hints."""
    import datetime as dt
    rng = np.random.default_rng(50_000 + seed)
    entries = []
    for _ in range(int(rng.integers(5, 9))):
        days = int(rng.integers(10, 400))
        entries.append({"date": alarm_date - dt.timedelta(days=days), "text": str(rng.choice(ROUTINE))})
    for h, texts in HINTS.items():
        p = P_TRUE_HINT if h == hypothesis else P_FALSE_HINT
        if rng.random() < p:
            days = int(rng.integers(1, 20)) if h in ("bearing_wear", "ambient") else int(rng.integers(5, 90))
            entries.append({"date": alarm_date - dt.timedelta(days=days), "text": str(rng.choice(texts))})
    entries.sort(key=lambda e: e["date"])
    return [{"date": e["date"].strftime("%Y-%m-%d"), "text": e["text"]} for e in entries]


ALL_DOCS = {**MANUAL, **KB}


def list_docs():
    return [{"id": k, "title": v.splitlines()[0][:90]} for k, v in ALL_DOCS.items()]


def search_docs(query: str, k: int = 3):
    terms = [t for t in query.lower().split() if len(t) > 2]
    scored = []
    for doc_id, text in ALL_DOCS.items():
        low = text.lower()
        s = sum(low.count(t) for t in terms)
        if s:
            scored.append((s, doc_id))
    scored.sort(reverse=True)
    return [{"id": d, "score": s} for s, d in scored[:k]]
